// ===================
//    Operator Java
// ===================

public class Operator {

    public static void main(String[] args) {
        // === Operator Aritmatika ===
        int a = 10;
        int b = 5;
        
        // > penjumlahan
        int penjumlahan = a + b;
        System.out.println("Hasil penjumlahan " + a + " + " + b + " = " + penjumlahan);
        
        
        // > pengurangan
        int pengurangan = a - b;
        System.out.println("Hasil penjumlahan " + a + " - " + b + " = " + pengurangan);
        
        
        // > perkalian
        int perkalian = a * b;
        System.out.println("Hasil perkalian " + a + " * " + b + " = " + perkalian);
        
        
        // > pembagian
        int pembagian = a / b;
        System.out.println("Hasil pembagian " + a + " / " + b + " = " + pembagian);
        
        
        // > modulus
        int modulus = a % b;
        System.out.println("Sisa bagi " + a + " % " + b + " = " + modulus);
    }
    
}
